# A string of a VENDOR.json that the script can pass to a command as an argument, holding
# U+0000 or a surrogate code point. json.dumps writes each as an escape, \u0000 or \ud800, and
# json.loads reads that escape back as the one character, so the file still parses.
NUL = "which a command-line argument cannot hold"
SURROGATE = "a surrogate code point, which UTF-8 cannot encode"


def assert_one_usage_error(proc: subprocess.CompletedProcess, line: str):
    assert proc.returncode == 2, proc.stdout + proc.stderr
    assert proc.stdout == ""
    assert proc.stderr.splitlines() == [f"usage error: {line}"]


@pytest.mark.parametrize("source, name, problem", [
    (COPIES, "a\x00b", f"character 2 is U+0000, {NUL}"),
    (COPIES, "a\ud800b", f"character 2 is U+D800, {SURROGATE}"),
    # subprocess passes U+DC80 on as the byte 0x80 rather than refusing it.
    (COPIES, "a\udc80b", f"character 2 is U+DC80, {SURROGATE}"),
    (SCENARIOS, "a\x00b", f"character 2 is U+0000, {NUL}"),
    (PACKAGE, "a\ud800b.json", f"character 2 is U+D800, {SURROGATE}"),
])
def test_a_file_name_holding_nul_or_a_surrogate_is_a_usage_error(tree, source, name, problem):
    index = len(tree.manifests[source]["files"])
    tree.manifests[source]["files"] = tree.manifests[source]["files"] + [name]
    tree.save()
    assert_one_usage_error(tree.check(), f"vendor/{source}/VENDOR.json files[{index}] cannot "
                                         f"be passed to a command ({problem})")


@pytest.mark.parametrize("source, key, char", [
    (COPIES, "commit", "\ud800"),
    (COPIES, "commit", "\x00"),
    (COPIES, "version", "\x00"),
    (SCENARIOS, "commit", "\x00"),
    (COPIES, "repo", "\udfff"),
    (PACKAGE, "package", "\x00"),
    (PACKAGE, "version", "\ud800"),
    (PACKAGE, "registry", "\x00"),
])
def test_a_pin_holding_nul_or_a_surrogate_is_a_usage_error(tree, source, key, char):
    if key == "repo" or source == PACKAGE:
        # These reach a command only when the source is fetched from where its pin says.
        del tree.overrides[source]
    value = tree.manifests[source][key] + char
    tree.manifests[source][key] = value
    tree.save()
    problem = NUL if char == "\x00" else SURROGATE
    assert_one_usage_error(tree.check(), f"vendor/{source}/VENDOR.json {key} cannot be passed "
                                         f"to a command (character {len(value)} is "
                                         f"U+{ord(char):04X}, {problem})")


def test_a_file_name_holding_other_text_is_compared(tree):
    # json.dumps writes U+10000 as the escapes 𐀀, a pair, which json.loads reads
    # back as that one character. The upstream holds no such file, so it is drift.
    name = "café-\U00010000.json"
    tree.manifests[COPIES]["files"] = tree.manifests[COPIES]["files"] + [name]
    tree.save()
    proc = tree.check()
    assert proc.returncode == 1, proc.stdout + proc.stderr
    assert lines(proc) == [f"DRIFT {COPIES} {name}"]


# Without -z, git ls-tree prints each of these names quoted: café.json while core.quotePath is
# true, its default, and the other three whatever core.quotePath is.
@pytest.mark.parametrize("name", ["café.json", 'say "hi".json', "back\\slash.json",
                                  "tab\there.json"],
                         ids=["non-ascii", "double-quote", "backslash", "tab"])
def test_a_file_name_that_git_quotes_is_found_at_the_pin(tree, name):
    work = tree.copies_work
    (work / name).write_bytes(b"{}\n")
    run(GIT + ["-C", str(work), "add", "--", name])
    run(GIT + ["-C", str(work), "commit", "-q", "-m", "a name git quotes"])
    run(GIT + ["--git-dir", str(tree.copies_bare), "fetch", "-q", str(work),
               "refs/heads/main:refs/heads/main"])
    # The tag v9.9.9 names the first commit, so the new pin carries no version.
    tree.manifests[COPIES].update(
        commit=run(["git", "-C", str(work), "rev-parse", "HEAD"]).stdout.strip(),
        version=None, files=tree.manifests[COPIES]["files"] + [name])
    (tree.root / "vendor" / COPIES / name).write_bytes(b"{}\n")
    tree.save()
    proc = tree.check()
    assert proc.returncode == 0, proc.stdout + proc.stderr
    assert lines(proc) == ["OK: 7 vendored files in 3 sources match their sources at the pin"]
    # A changed byte in that file is drift the compare finds, with the file found at the pin.
    tree.flip_byte(COPIES, name)
    proc = tree.check()
    assert proc.returncode == 1, proc.stdout + proc.stderr
    assert lines(proc) == [f"DRIFT {COPIES} {name}"]
    assert f"{name} is not in" not in proc.stderr


def pin_a_commit_holding(tree, files: dict, name: str, vendored: bytes):
    """Commit files to the aiis-signatures upstream, pin that commit and add name, vendored as
    the bytes vendored, to files of the pin."""
    work = tree.copies_work
    for rel, data in files.items():
        (work / rel).write_bytes(data)
    # git add reads a pathspec that starts with a colon as magic; ./ keeps each one a path.
    run(GIT + ["-C", str(work), "add", "--", *(f"./{rel}" for rel in files)])
    run(GIT + ["-C", str(work), "commit", "-q", "-m", "a commit for the pin"])
    run(GIT + ["--git-dir", str(tree.copies_bare), "fetch", "-q", str(work),
               "refs/heads/main:refs/heads/main"])
    # The tag v9.9.9 names the first commit, so the new pin carries no version.
    tree.manifests[COPIES].update(
        commit=run(["git", "-C", str(work), "rev-parse", "HEAD"]).stdout.strip(),
        version=None, files=tree.manifests[COPIES]["files"] + [name])
    (tree.root / "vendor" / COPIES / name).write_bytes(vendored)
    tree.save()


# git 2.53.0 reads a pathspec that starts with a colon as magic: git ls-tree lists colon.json
# for :colon.json and x.json for :(top)x.json, and exits 128 on :!x.json, whose magic it does
# not support. The commit holds colon.json and x.json beside the name, with other bytes.
@pytest.mark.parametrize("name", [":colon.json", ":(top)x.json", ":!x.json"],
                         ids=["colon", "top", "exclude"])
def test_a_file_name_starting_with_a_colon_is_found_at_the_pin(tree, name):
    pin_a_commit_holding(tree, {name: b"{}\n", "colon.json": b"[]\n", "x.json": b"[]\n"},
                         name, b"{}\n")
    proc = tree.check()
    assert proc.returncode == 0, proc.stdout + proc.stderr
    assert lines(proc) == ["OK: 7 vendored files in 3 sources match their sources at the pin"]
    # A changed byte in that file is drift the compare finds, with the file found at the pin.
    tree.flip_byte(COPIES, name)
    proc = tree.check()
    assert proc.returncode == 1, proc.stdout + proc.stderr
    assert lines(proc) == [f"DRIFT {COPIES} {name}"]
    assert f"{name} is not in" not in proc.stderr


@pytest.mark.parametrize("name, found", [(":colon.json", "colon.json"),
                                         (":(top)x.json", "x.json")], ids=["colon", "top"])
def test_a_commit_holding_only_the_path_the_magic_names_is_drift(tree, name, found):
    # The commit holds the file a listing that reads the name as magic finds, with the bytes
    # vendored as the name, and no file of that name.
    pin_a_commit_holding(tree, {found: b"{}\n"}, name, b"{}\n")
    proc = tree.check()
    assert proc.returncode == 1, proc.stdout + proc.stderr
    assert lines(proc) == [f"DRIFT {COPIES} {name}"]
    commit = tree.manifests[COPIES]["commit"]
    assert f"{COPIES}: {name} is not in {commit}" in proc.stderr.splitlines()


# Runs the script on an interpreter whose tarfile has no extraction filters, as Python 3.9.6
# has: no tarfile.data_filter, and an extractall that takes no filter argument.
NO_FILTERS = """\
import runpy, sys, tarfile
del tarfile.data_filter
extractall = tarfile.TarFile.extractall
def old_extractall(self, path=".", members=None, *, numeric_owner=False):
    return extractall(self, path, members, numeric_owner=numeric_owner)
tarfile.TarFile.extractall = old_extractall
sys.argv = sys.argv[1:]
runpy.run_path(sys.argv[0], run_name="__main__")
"""


def check_without_filters(tree) -> subprocess.CompletedProcess:
    argv = [sys.executable, "-c", NO_FILTERS, str(SCRIPT), str(tree.root), "--retry-delay", "0"]
    for source, location in tree.overrides.items():
        argv += ["--override", f"{source}={location}"]
    return subprocess.run(argv, capture_output=True, text=True, timeout=600, env=offline_env())


def test_a_python_without_tarfile_filters_is_a_usage_error_with_a_package_source(tree):
    proc = check_without_filters(tree)
    assert proc.returncode == 2, proc.stdout + proc.stderr
    assert proc.stdout == ""
    assert "usage error:" in proc.stderr and "no extraction filters" in proc.stderr
    assert "Traceback" not in proc.stderr


def test_a_python_without_tarfile_filters_checks_git_sources_alone(tree):
    shutil.rmtree(tree.root / "vendor" / PACKAGE)
    del tree.overrides[PACKAGE]
    proc = check_without_filters(tree)
    assert proc.returncode == 0, proc.stdout + proc.stderr
    assert lines(proc) == ["OK: 3 vendored files in 2 sources match their sources at the pin"]


