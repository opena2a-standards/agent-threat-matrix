def offline_env() -> dict:
    env = dict(os.environ)
    env["GIT_ALLOW_PROTOCOL"] = "file"
    env["npm_config_offline"] = "true"
    return env


def run(argv: list, **kwargs) -> subprocess.CompletedProcess:
    return subprocess.run(argv, capture_output=True, text=True, timeout=300, check=True,
                          env=offline_env(), **kwargs)


def upstream(tmp: Path, name: str, files: dict, tag=None) -> tuple:
    """A bare repository holding files in one commit, and that commit."""
    work = tmp / f"{name}-work"
    work.mkdir()
    run(GIT + ["init", "-q", str(work)])
    for rel, data in files.items():
        path = work / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(data)
    run(GIT + ["-C", str(work), "add", "--", *files])
    run(GIT + ["-C", str(work), "commit", "-q", "-m", "upstream"])
    if tag:
        run(GIT + ["-C", str(work), "tag", tag])
    commit = run(["git", "-C", str(work), "rev-parse", "HEAD"]).stdout.strip()
    bare = tmp / f"{name}.git"
    run(["git", "clone", "-q", "--bare", str(work), str(bare)])
    return bare, commit, work


def tarball(path: Path, files: dict):
    with tarfile.open(path, "w:gz") as archive:
        for name, data in files.items():
            info = tarfile.TarInfo(name)
            info.size = len(data)
            info.mode = 0o644
            archive.addfile(info, io.BytesIO(data))


def integrity(path: Path) -> str:
    return "sha512-" + base64.b64encode(hashlib.sha512(path.read_bytes()).digest()).decode()


def write_manifest(root: Path, source: str, manifest: dict):
    (root / "vendor" / source / "VENDOR.json").write_bytes(dumped(manifest))


class Tree:
    """A scratch root, its upstreams and the overrides that point the script at them."""

    def __init__(self, tmp: Path):
        if shutil.which("node") is None:
            pytest.skip("node is not installed; the package source runs generate.mjs")
        self.tmp = tmp
        self.root = tmp / "root"
        vendor = self.root / "vendor"

        self.copies_bare, self.copies_commit, self.copies_work = upstream(
            tmp, COPIES, {**COPIED_FILES, "README.md": b"not vendored\n"}, tag="v9.9.9")
        for rel, data in COPIED_FILES.items():
            (vendor / COPIES / rel).parent.mkdir(parents=True, exist_ok=True)
            (vendor / COPIES / rel).write_bytes(data)
        self.manifests = {COPIES: {
            "repo": "example/aiis-signatures", "commit": self.copies_commit,
            "version": "v9.9.9", "read": READ, "files": sorted(COPIED_FILES),
            "refresh": "git show <commit>:<path> > vendor/aiis-signatures/<path>"}}

        self.scenarios_bare, self.scenarios_commit, self.scenarios_work = upstream(
            tmp, SCENARIOS, SCENARIO_FILES)
        (vendor / SCENARIOS).mkdir(parents=True)
        shutil.copyfile(DVAA_GENERATOR, vendor / SCENARIOS / "generate.py")
        (vendor / SCENARIOS / "expected-checks.json").write_bytes(SCENARIO_OUTPUT)
        self.manifests[SCENARIOS] = {
            "repo": "example/damn-vulnerable-ai-agent", "commit": self.scenarios_commit,
            "version": None, "read": READ, "files": ["expected-checks.json"],
            "generate": "python3 -I vendor/damn-vulnerable-ai-agent/generate.py <dir> <commit> "
                        "expected-checks.json"}

        self.tarball = tmp / "hackmyagent-0.33.2.tgz"
        tarball(self.tarball, PACKAGE_FILES)
        (vendor / PACKAGE).mkdir(parents=True)
        shutil.copyfile(HMA_GENERATOR, vendor / PACKAGE / "generate.mjs")
        for name, data in PACKAGE_OUTPUTS.items():
            (vendor / PACKAGE / name).write_bytes(data)
        self.manifests[PACKAGE] = {
            "package": "hackmyagent", "version": "0.33.2",
            "registry": "https://registry.npmjs.org", "integrity": integrity(self.tarball),
            "read": READ, "files": sorted(PACKAGE_OUTPUTS),
            "generate": "env -i PATH=\"$PATH\" node vendor/hackmyagent/generate.mjs <dir>/package "
                        "<name>"}
        self.save()
        self.overrides = {COPIES: str(self.copies_bare), SCENARIOS: str(self.scenarios_bare),
                          PACKAGE: str(self.tarball)}

    def save(self):
        for source, manifest in self.manifests.items():
            write_manifest(self.root, source, manifest)

    def flip_byte(self, source: str, rel: str):
        path = self.root / "vendor" / source / rel
        data = bytearray(path.read_bytes())
        index = data.index(b"0") if b"0" in data else 0
        data[index] = ord("1") if data[index] == ord("0") else ord("0")
        path.write_bytes(bytes(data))

    def check(self, *extra: str) -> subprocess.CompletedProcess:
        argv = [sys.executable, str(SCRIPT), str(self.root), "--retry-delay", "0"]
        for source, location in self.overrides.items():
            argv += ["--override", f"{source}={location}"]
        return subprocess.run(argv + list(extra), capture_output=True, text=True, timeout=600,
                              env=offline_env())


