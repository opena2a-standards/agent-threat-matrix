"""scripts/check_vendor_integrity.py compares every vendored input with its source at the pin.

Each test builds a scratch repository root holding three sources under vendor/, the three
kinds the crosswalk reads: a git source of byte-exact copies (``refresh``), a git source
regenerated by its ``generate.py``, and a package regenerated by its ``generate.mjs``. The
generators are the ones this repository ships. The upstreams are a local bare repository per
git source and a local tarball for the package, passed with ``--override``. git is limited to
the file protocol and npm runs offline, so no test opens a network connection.

The script exits 0 when every file matches, 1 with a ``DRIFT <source> <file>`` line per
difference, 3 with an ``UNREACHABLE`` line per source it could not fetch after three attempts
(comparing nothing for it), and 2 on a usage error.
"""

