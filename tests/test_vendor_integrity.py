def test_a_tag_that_names_another_commit_is_drift(tree):
    # The upstream gains a commit and tags it; the pin names that tag with the old commit.
    work = tree.copies_work
    (work / "README.md").write_bytes(b"a later commit\n")
    run(GIT + ["-C", str(work), "commit", "-q", "-am", "later"])
    run(GIT + ["-C", str(work), "tag", "v9.9.10"])
    run(GIT + ["--git-dir", str(tree.copies_bare), "fetch", "-q", str(work),
               "refs/tags/v9.9.10:refs/tags/v9.9.10"])
    tree.manifests[COPIES]["version"] = "v9.9.10"
    tree.save()
    proc = tree.check()
    assert proc.returncode == 1, proc.stdout + proc.stderr
    assert lines(proc) == [f"DRIFT {COPIES} VENDOR.json"]
    assert f"tag v9.9.10 does not name {tree.copies_commit}" in proc.stderr


