def test_an_unreachable_upstream_exits_3_and_compares_nothing(tree):
    # Every vendored file differs from its source, so a compare would print DRIFT lines.
    tree.flip_byte(COPIES, "retired-ids.yaml")
    tree.flip_byte(SCENARIOS, "expected-checks.json")
    tree.flip_byte(PACKAGE, "check-ids.json")
    missing = tree.tmp / "absent"
    tree.overrides = {COPIES: str(missing / "copies.git"), SCENARIOS: str(missing / "scenarios.git"),
                      PACKAGE: str(missing / "hackmyagent-0.33.2.tgz")}
    proc = tree.check()
    assert proc.returncode == 3, proc.stdout + proc.stderr
    assert lines(proc) == [f"UNREACHABLE {source}: upstream unreachable, drift not measured"
                           for source in (COPIES, SCENARIOS, PACKAGE)]
    for source in (COPIES, SCENARIOS, PACKAGE):
        assert f"{source}: " in proc.stderr and "attempt 3 of 3 failed" in proc.stderr
        assert sum(line.startswith(f"{source}: ") and "attempt " in line
                   for line in proc.stderr.splitlines()) == 3


def test_drift_beside_an_unreachable_upstream_exits_1(tree):
    tree.flip_byte(PACKAGE, "payload-ids.json")
    tree.overrides[COPIES] = str(tree.tmp / "absent.git")
    proc = tree.check()
    assert proc.returncode == 1, proc.stdout + proc.stderr
    assert lines(proc) == [f"UNREACHABLE {COPIES}: upstream unreachable, drift not measured",
                           f"DRIFT {PACKAGE} payload-ids.json"]


